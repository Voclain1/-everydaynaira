#!/usr/bin/env node
/**
 * Writes docs/image-prompts.md: one art-directed prompt per post, all in the
 * same visual language as the site (isometric, matte, off-white, lime + charcoal).
 * Paste a prompt into Midjourney, Ideogram, Flux, or ChatGPT image generation.
 *
 *   npm run images:prompts              # all posts
 *   npm run images:prompts -- <slug>    # one post
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = process.cwd();
const only = process.argv[2];

const STYLE =
  "isometric 3D illustration, clean matte clay render, soft studio light from top left, off-white background (#F3F2ED), " +
  "palette limited to warm white, stone grey, charcoal (#1A2329) and one acid-lime accent (#D4EE4A), thin dark outlines, " +
  "generous negative space, objects arranged on a subtle dotted grid floor, editorial, minimal, premium fintech magazine style, " +
  "no text, no logos, no people's faces, 16:10";

const SCENES = {
  budgeting: "a monthly budget laid out as stacked blocks of naira notes split into three unlabelled piles, a notebook and a pen beside a smartphone calculator",
  savings: "a rising staircase of savings jars and naira coin stacks, the tallest one lime, a small padlocked piggy bank",
  banking: "a Nigerian bank card, a POS terminal and a smartphone showing a generic banking app, small receipt slips curling off the terminal",
  debt: "a loan agreement folder with a magnifying glass, blocks shrinking step by step as a debt is paid down",
  income: "a laptop, a market trader's cash box and a salary envelope arranged as uneven bars of different heights",
  "money-safety": "a smartphone inside a protective glass cube with a shield-shaped lime block, a fake SMS bubble cracked in half",
};

const posts = fs
  .readdirSync(path.join(ROOT, "content/posts"))
  .filter((f) => f.endsWith(".md"))
  .map((f) => matter(fs.readFileSync(path.join(ROOT, "content/posts", f), "utf8")).data)
  .filter((d) => !only || d.slug === only);

const out = [
  "# Cover image prompts",
  "",
  "Generated by `npm run images:prompts`. Every post already has a generated isometric cover; use these only when you want a richer rendered image.",
  "",
  `**Shared style (keep it identical across every image):** ${STYLE}`,
  "",
];
for (const p of posts) {
  out.push(`## ${p.title}`, "", `Save as: \`image-inbox/${p.slug}.png\``, "", "```", `${SCENES[p.category] ?? SCENES.budgeting}, illustrating "${p.title}" for Nigerian readers. ${STYLE}`, "```", "");
}
fs.writeFileSync(path.join(ROOT, "docs/image-prompts.md"), out.join("\n"));
console.log(`Wrote ${posts.length} prompt(s) to docs/image-prompts.md`);
