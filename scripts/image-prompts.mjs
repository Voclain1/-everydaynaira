#!/usr/bin/env node
/**
 * Writes docs/image-prompts.md: one photography prompt per post.
 * Each prompt = the post's scene brief (content/image-briefs.json) + one shared
 * photographic style block, so images made on different days still look like one series.
 *
 *   npm run images:prompts              # all posts
 *   npm run images:prompts -- <slug>    # one post
 *
 * Add a brief to content/image-briefs.json whenever you publish a new post.
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = process.cwd();
const only = process.argv[2];
const briefs = JSON.parse(fs.readFileSync(path.join(ROOT, "content/image-briefs.json"), "utf8"));

export const STYLE =
  "Editorial documentary photograph set in Nigeria, real everyday life, unposed. " +
  "Shot on a full-frame camera with a 35mm lens at f/2.0, natural available light, gentle shadows, " +
  "true-to-life colour with warm neutral tones and slightly muted saturation, fine natural film grain, " +
  "realistic skin texture and pores, natural hands with five fingers, authentic Nigerian clothing, homes and streets. " +
  "Composition with the subject in the centre third and calm space around it. " +
  "No text, no readable screens, no logos or brand names, no watermarks.";

export const NEGATIVE =
  "illustration, 3D render, CGI, cartoon, painting, plastic skin, airbrushed, HDR, oversaturated, " +
  "studio backdrop, stock-photo smile, looking at camera, extra fingers, distorted hands, garbled text, " +
  "logos, watermark, western suburban setting";

const posts = fs
  .readdirSync(path.join(ROOT, "content/posts"))
  .filter((f) => f.endsWith(".md"))
  .map((f) => matter(fs.readFileSync(path.join(ROOT, "content/posts", f), "utf8")).data)
  .filter((d) => !only || d.slug === only);

const missing = posts.filter((p) => !briefs[p.slug]).map((p) => p.slug);

const out = [
  "# Photo prompts",
  "",
  "Generated by `npm run images:prompts`. Paste a prompt into your image tool, generate at **16:10**, and save the best result as `image-inbox/<slug>.png` (or .jpg). Then run `npm run images:optimize`.",
  "",
  "**Recommended settings**",
  "",
  "- Midjourney: append `--ar 16:10 --style raw --stylize 50` and paste the avoid-list after `--no`.",
  "- ChatGPT / GPT image, Google Gemini or Imagen, Ideogram: set the aspect ratio to 16:10 (or 3:2) and paste the prompt as is, followed by \"Avoid: …\".",
  "- Flux: use raw or photo mode if your tool offers it.",
  "",
  `**Shared style (already inside every prompt):** ${STYLE}`,
  "",
  `**Avoid:** ${NEGATIVE}`,
  "",
];
if (missing.length) out.push(`> Missing briefs for: ${missing.join(", ")}. Add them to content/image-briefs.json.`, "");

for (const p of posts) {
  const b = briefs[p.slug];
  if (!b) continue;
  out.push(
    `## ${p.title}`,
    "",
    `Save as \`image-inbox/${p.slug}.png\` · alt text: "${b.alt}"`,
    "",
    "```",
    `${b.scene}. ${STYLE}`,
    "```",
    "",
  );
}
fs.writeFileSync(path.join(ROOT, "docs/image-prompts.md"), out.join("\n"));
console.log(`Wrote ${posts.length - missing.length} prompt(s) to docs/image-prompts.md${missing.length ? `; ${missing.length} post(s) need a brief` : ""}`);
